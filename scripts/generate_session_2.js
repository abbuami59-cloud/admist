let updatedCount = 0;

for (const rev of session2Reviews) {
  const filePath = path.join(REVIEWS_DIR, rev.slug + '.json');
  let originalData = {};
  if (fs.existsSync(filePath)) {
    try {
      originalData = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    } catch (e) {
      console.log('Error reading original:', rev.slug);
    }
  }

  const updatedData = {
    id: originalData.id || 0,
    slug: rev.slug,
    title: rev.title,
    content: rev.content.trim()
  };

  fs.writeFileSync(filePath, JSON.stringify(updatedData, null, 2), 'utf8');
  updatedCount++;
}

console.log(`Successfully updated ${updatedCount} reviews for Session 2!`);
